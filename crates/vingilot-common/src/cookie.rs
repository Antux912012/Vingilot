use std::fs::OpenOptions;
use std::io::{self, Write};
use std::path::Path;
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;

use serde::{Deserialize, Serialize};

/// Standard Netscape HTTP cookie structure (used by yt-dlp, cURL, and browser engines).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NetscapeCookie {
    pub domain: String,
    pub include_subdomains: bool,
    pub path: String,
    pub is_secure: bool,
    pub expires: i64,
    pub name: String,
    pub value: String,
}

impl NetscapeCookie {
    pub fn new(
        domain: impl Into<String>,
        include_subdomains: bool,
        path: impl Into<String>,
        is_secure: bool,
        expires: i64,
        name: impl Into<String>,
        value: impl Into<String>,
    ) -> Self {
        Self {
            domain: domain.into(),
            include_subdomains,
            path: path.into(),
            is_secure,
            expires,
            name: name.into(),
            value: value.into(),
        }
    }
}

/// Parses a Netscape formatted cookie string (standard cookies.txt format).
pub fn parse_netscape_cookies(content: &str) -> Vec<NetscapeCookie> {
    let mut cookies = Vec::new();
    for raw_line in content.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let parts: Vec<&str> = line.split('\t').collect();
        if parts.len() < 7 {
            continue;
        }

        let domain = parts[0].to_string();
        let include_subdomains = parts[1].eq_ignore_ascii_case("true");
        let path = parts[2].to_string();
        let is_secure = parts[3].eq_ignore_ascii_case("true");
        let expires = parts[4].parse::<i64>().unwrap_or(0);
        let name = parts[5].to_string();
        let value = parts[6].to_string();

        cookies.push(NetscapeCookie {
            domain,
            include_subdomains,
            path,
            is_secure,
            expires,
            name,
            value,
        });
    }
    cookies
}

/// Serializes a slice of `NetscapeCookie` items to standard Netscape cookies.txt format.
pub fn serialize_netscape_cookies(cookies: &[NetscapeCookie]) -> String {
    let mut out = String::from("# Netscape HTTP Cookie File\n# Generated by Vingilot Unified Harvester\n\n");
    for c in cookies {
        out.push_str(&format!(
            "{}\t{}\t{}\t{}\t{}\t{}\t{}\n",
            c.domain,
            if c.include_subdomains { "TRUE" } else { "FALSE" },
            c.path,
            if c.is_secure { "TRUE" } else { "FALSE" },
            c.expires,
            c.name,
            c.value
        ));
    }
    out
}

/// Writes cookie text to a file with strict permissions (0600 on Unix) to prevent local session theft.
pub fn save_cookies_file_secure(path: &Path, content: &str) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
        #[cfg(unix)]
        {
            let _ = std::fs::set_permissions(parent, std::fs::Permissions::from_mode(0o700));
        }
    }

    let mut file = OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(true)
        .open(path)?;

    #[cfg(unix)]
    {
        file.set_permissions(std::fs::Permissions::from_mode(0o600))?;
    }

    file.write_all(content.as_bytes())?;
    file.flush()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_and_serialize_netscape_cookies() {
        let raw = "\
# Netscape HTTP Cookie File
.youtube.com\tTRUE\t/\tTRUE\t1893456000\tSID\tsecret_sid_token
.youtube.com\tTRUE\t/\tTRUE\t1893456000\tHSID\tsecret_hsid_token
example.com\tFALSE\t/app\tFALSE\t0\tsession\tsession_123
";
        let parsed = parse_netscape_cookies(raw);
        assert_eq!(parsed.len(), 3);
        assert_eq!(parsed[0].domain, ".youtube.com");
        assert_eq!(parsed[0].name, "SID");
        assert_eq!(parsed[0].value, "secret_sid_token");
        assert!(parsed[0].include_subdomains);
        assert!(parsed[0].is_secure);

        let serialized = serialize_netscape_cookies(&parsed);
        let reparsed = parse_netscape_cookies(&serialized);
        assert_eq!(parsed, reparsed);
    }

    #[test]
    fn test_secure_cookie_file_permissions() {
        let temp = tempfile::tempdir().unwrap();
        let cookie_file = temp.path().join("secure_cookies.txt");
        save_cookies_file_secure(&cookie_file, "TEST_COOKIE_PAYLOAD").unwrap();
        assert!(cookie_file.exists());

        #[cfg(unix)]
        {
            let meta = std::fs::metadata(&cookie_file).unwrap();
            let mode = meta.permissions().mode() & 0o777;
            assert_eq!(mode, 0o600);
        }
    }
}
